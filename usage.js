  function inject(){
    Object.keys(USAGE).forEach(function(id){
      var sec = document.getElementById('s-'+id);
      if(!sec) return;
      var first = sec.querySelector('.card');
      if(!first) return;
      if(sec.querySelector('.usage-card')) return; // 避免重复
      var items = USAGE[id].map(function(t){ return '<li>'+t+'</li>'; }).join('');
      var card = document.createElement('div');
      card.className = 'card usage-card';
      card.style.marginTop = '14px';
      card.innerHTML = '<div class="card-title"><div class="dot"></div>使用说明</div><ul class="usage-list">'+items+'</ul>';
      // 如果首卡位于 panel-grid 内，把「使用说明」插到 panel-grid 之后，
      // 避免 grid 变成 3 列产生右侧大段空白。
      var panel = first.closest ? first.closest('.panel-grid') : null;
      if(panel && panel.parentNode === sec){
        panel.insertAdjacentElement('afterend', card);
      } else {
        first.insertAdjacentElement('afterend', card);
      }
    });
  }

  if(document.readyState === 'loading'){
    document.addEventListener('DOMContentLoaded', inject);
  } else {
    inject();
  }
