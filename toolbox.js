  var state = { cat: 'all', kw: '', open: {} };

  function $(id) { return document.getElementById(id); }
  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }
  /* 步骤与说明里允许少量 HTML（<b>/<code>/<br>），只做标签白名单过滤 */
  function allow(s) {
    return String(s == null ? '' : s)
      .replace(/<(?!\/?(b|strong|code|br|i|em)(\s|>|\/))/gi, '&lt;');
  }

  function match(t, kw) {
    if (!kw) return true;
    var ex = (t.examples || []).map(function (e) { return e.t + ' ' + (e.d || '') + ' ' + (e.c || ''); }).join(' ');
    var hay = (t.name + ' ' + t.full + ' ' + t.desc + ' ' + t.cat + ' ' +
               t.tags.join(' ') + ' ' + (t.scenes || []).join(' ') + ' ' + ex).toLowerCase();
    return hay.indexOf(kw.toLowerCase()) >= 0;
  }

  function render() {
    var box = $('tb-list');
    if (!box) return;
    var list = TOOLS.filter(function (t) {
      return (state.cat === 'all' || t.cat === state.cat) && match(t, state.kw);
    });

    if (!list.length) {
      box.innerHTML = '<div class="rst-empty">没有匹配的工具，换个关键词试试。</div>';
      return;
    }

    var h = '';
    CATS.forEach(function (c) {
      var sub = list.filter(function (t) { return t.cat === c; });
      if (!sub.length) return;
      h += '<div class="tb-cat"><span class="tb-cat-dot"></span>' + esc(c) +
           '<span class="tb-cat-n">' + sub.length + '</span></div>';
      sub.forEach(function (t) { h += cardHTML(t); });
    });
    box.innerHTML = h;
  }

  /* 一段示例：标题 + 说明 + 代码块（带复制按钮） */
