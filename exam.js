  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }
  function norm(s) { return String(s || '').toLowerCase().split('').sort().join(''); }
  function isCorrect(q, sel) {
    if (q.type === 'multi') return norm(sel) === norm(q.ans);
    return sel === q.ans;
  }
