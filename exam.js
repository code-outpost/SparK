  function questionCard(q, sel) {
    var typeName = q.type === 'judge' ? '判断题' : (q.type === 'single' ? '单选题' : '多选题');
    var answered = sel != null;
    var correct = answered && isCorrect(q, sel);
    var h = '<div class="exam-q">';
    h += '<div class="exam-q-head"><span class="exam-q-type t-' + q.type + '">' + typeName + '</span>' +
         '<span class="exam-q-cat">' + esc(q.cat) + '</span>' +
         '<span class="exam-q-no">#' + q.id + '</span></div>';
    h += '<div class="exam-q-text">' + esc(q.q) + '</div>';
    h += '<div class="exam-opts">';
    OPTS.forEach(function (k) {
      if (optText(q, k) === '') return;
      var cls = 'exam-opt';
      if (answered) {
        if (k === q.ans) cls += ' right';
        else if (k === sel) cls += ' wrong';
      }
      // id 必须用引号包裹：导入题的 id 是 'imp1' 这类字符串，裸写会变成未定义变量
      h += '<button class="' + cls + '" onclick="examAnswer(\'' + q.id + '\',\'' + k + '\')">' +
           '<span class="exam-opt-lab">' + LAB[k] + '</span>' +
           '<span class="exam-opt-txt">' + esc(optText(q, k)) + '</span></button>';
    });
    h += '</div>';
    if (answered) {
      h += '<div class="exam-result ' + (correct ? 'ok' : 'bad') + '">' +
           (correct ? '✓ 回答正确' : '✗ 正确答案：' + LAB[q.ans]) + '</div>';
      h += '<div class="exam-exp"><b>解析：</b>' + esc(q.exp) + '</div>';
    }
    h += '</div>';
    return h;
  }

