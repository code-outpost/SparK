  window.examImportFile = function (input) {
    var f = input && input.files && input.files[0];
    if (!f) return;
    if (typeof FileReader === 'undefined') {
      S.impMsg = '<span class="bad">当前环境不支持读取文件，请改用粘贴文本</span>';
      S.showImport = true; render(); return;
    }
    var fr = new FileReader();
    fr.onload = function () { doImport(String(fr.result || '')); };
    fr.onerror = function () { S.impMsg = '<span class="bad">文件读取失败</span>'; render(); };
    fr.readAsText(f, 'utf-8');
    try { input.value = ''; } catch (e) { /* 忽略 */ }
  };

